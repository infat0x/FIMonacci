"""
AI Timeline Analysis Module
Uses Mistral AI to analyze combined FIM + Wazuh SIEM data
"""

import os
import json
from typing import Dict, List, Optional
from datetime import datetime, timezone
from mistralai import Mistral

# Mistral configuration
MODEL_ID = os.environ.get("MISTRAL_MODEL", "mistral-small-latest")

